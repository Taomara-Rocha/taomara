package com.example.estruturaRepeticao;

//Usando while Mostre os números de 1 a 30, um por linha

public class Exercicio3 {

    public static void main(String[] args) {

        int i = 1;
        while (i <= 30) {
            System.out.println(i);
            i++;
        }
    }
} //Nesse exercício foi necessáio inserir mais linhas para explicar o código, pois o while precisa de uma variável para ser inicializada e depois incrementada, diferente do for que já faz isso de forma automática.